<?php
/** Build search assets with a stable CSS filename for prototyping. */
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
$root = dirname(__DIR__) . '/search';
$directory = $root . '/dist';
if (!is_dir($directory) && !mkdir($directory, 0755, true)) throw new RuntimeException('Could not create search asset directory.');
$old = is_file($root . '/manifest.php') ? require $root . '/manifest.php' : [];
$script = '';
foreach (['format.js', 'palette.js', 'zotero.js'] as $file) $script .= file_get_contents($root . '/' . $file) . "\n";
$style = file_get_contents($root . '/palette.css');
$manifest = [];
foreach (['script' => [$script, 'js'], 'style' => [$style, 'css']] as $kind => [$source, $extension]) {
    $name = $extension === 'css' ? 'search.css' : 'search-' . substr(hash('sha256', $source), 0, 12) . '.' . $extension;
    if (file_put_contents($directory . '/' . $name, $source) === false) throw new RuntimeException('Could not write search asset.');
    $manifest[$kind] = $name;
}
$temporary = $root . '/manifest.php.tmp';
if (file_put_contents($temporary, "<?php\n// Generated by bin/build-search.php.\nreturn " . var_export($manifest, true) . ";\n") === false || !rename($temporary, $root . '/manifest.php')) throw new RuntimeException('Could not publish search manifest.');
foreach (glob($directory . '/search-*') as $file) {
    if (!in_array(basename($file), array_merge(array_values($old), array_values($manifest)), true)) unlink($file);
}
echo "Built search JavaScript and CSS.\n";
